VALUES ('produtos', 'produtos', true)
ON CONFLICT (id) DO NOTHING;

-- Permitir visualização pública das imagens do bucket produtos
CREATE POLICY "Visualização pública de imagens no bucket produtos" 
ON storage.objects FOR SELECT 
TO public 
USING (bucket_id = 'produtos');
CREATE POLICY "Visualização pública de imagens" ON storage.objects FOR SELECT TO public USING (bucket_id = 'produtos');
CREATE POLICY "Upload para autenticados" ON storage.objects FOR INSERT TO authenticated WITH CHECK (bucket_id = 'produtos');
CREATE POLICY "Edição e exclusão para autenticados" ON storage.objects FOR UPDATE TO authenticated USING (bucket_id = 'produtos');
CREATE POLICY "Deleção para autenticados" ON storage.objects FOR DELETE TO authenticated USING (bucket_id = 'produtos');

-- Permitir upload/atualização/remoção para usuários autenticados no bucket produtos
CREATE POLICY "Upload permitido para autenticados no bucket produtos" 
ON storage.objects FOR INSERT 
TO authenticated 
WITH CHECK (bucket_id = 'produtos');

CREATE POLICY "Edição e exclusão de imagens para autenticados" 
ON storage.objects FOR UPDATE 
TO authenticated 
USING (bucket_id = 'produtos');

CREATE POLICY "Exclusão de imagens para autenticados" 
ON storage.objects FOR DELETE 
TO authenticated 
USING (bucket_id = 'produtos');

