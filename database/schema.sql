-- ============================================================
-- SCHEMA DO BANCO DE DADOS SUPABASE (PostgreSQL)
-- Vitrine Online & Painel Administrativo de Vendas
-- Arquitetura: VENDEDORA -> ESTOJO -> PRODUTOS -> VENDAS
-- ============================================================
