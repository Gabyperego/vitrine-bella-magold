-- Políticas para Acesso Público (Vitrine / Anon)
-- Qualquer cliente pode ver vendedoras ativas
CREATE POLICY "Permitir leitura pública de vendedoras ativas" 
ON public.vendedoras FOR SELECT 
TO anon, authenticated 
USING (status = 'Ativo' OR auth.role() = 'authenticated');
-- Políticas Públicas (Vitrine / Anon)
CREATE POLICY "Leitura pública de vendedoras ativas" ON public.sellers FOR SELECT TO anon, authenticated USING (ativo = true OR auth.role() = 'authenticated');
CREATE POLICY "Leitura pública de estojos ativos" ON public.cases FOR SELECT TO anon, authenticated USING (ativo = true OR auth.role() = 'authenticated');
CREATE POLICY "Leitura pública de categorias ativas" ON public.categories FOR SELECT TO anon, authenticated USING (ativo = true OR auth.role() = 'authenticated');
CREATE POLICY "Leitura pública de produtos disponíveis" ON public.products FOR SELECT TO anon, authenticated USING (ativo = true);

-- Qualquer cliente pode visualizar produtos
CREATE POLICY "Permitir leitura pública de produtos" 
ON public.produtos FOR SELECT 
TO anon, authenticated 
USING (true);
CREATE POLICY "Inserção pública de vendas pelo checkout" ON public.sales FOR INSERT TO anon, authenticated WITH CHECK (true);
CREATE POLICY "Inserção pública de itens de venda" ON public.sale_items FOR INSERT TO anon, authenticated WITH CHECK (true);

-- Clientes podem criar pedidos e itens ao finalizar compra pelo WhatsApp
CREATE POLICY "Permitir inserção pública de pedidos" 
ON public.pedidos FOR INSERT 
TO anon, authenticated 
WITH CHECK (true);
