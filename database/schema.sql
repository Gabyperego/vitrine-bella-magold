CREATE POLICY "Acesso total admin cases" ON public.cases FOR ALL TO authenticated USING (true) WITH CHECK (true);
CREATE POLICY "Acesso total admin categories" ON public.categories FOR ALL TO authenticated USING (true) WITH CHECK (true);
CREATE POLICY "Acesso total admin products" ON public.products FOR ALL TO authenticated USING (true) WITH CHECK (true);
CREATE POLICY "Acesso total admin sales" ON public.sales FOR ALL TO authenticated USING (true) WITH CHECK (true);
CREATE POLICY "Acesso total admin sale_items" ON public.sale_items FOR ALL TO authenticated USING (true) WITH CHECK (true);
CREATE POLICY "Acesso total admin case_closings" ON public.case_closings FOR ALL TO authenticated USING (true) WITH CHECK (true);

CREATE POLICY "Permitir inserção pública de itens de pedidos" 
ON public.pedido_itens FOR INSERT 
TO anon, authenticated 
WITH CHECK (true);

